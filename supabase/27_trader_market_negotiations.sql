-- Silsila migration 27: expiry and price negotiation for trader market posts.
begin;

alter table public.trader_market_posts
  add column if not exists expiry_date date,
  add column if not exists is_negotiable boolean not null default false;

create table if not exists public.trader_market_negotiations (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.trader_market_posts(id) on delete cascade,
  parent_id bigint references public.trader_market_negotiations(id) on delete set null,
  proposer_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  proposed_price numeric(14,2) not null check (proposed_price > 0),
  status text not null default 'pending'
    check (status in ('pending','accepted','rejected','countered')),
  created_at timestamptz not null default now(),
  constraint trader_market_negotiation_distinct_users check (proposer_id <> recipient_id)
);

create index if not exists trader_market_negotiations_post_created_idx
  on public.trader_market_negotiations(post_id, created_at);

alter table public.trader_market_negotiations enable row level security;

drop policy if exists trader_market_negotiations_participant_select
  on public.trader_market_negotiations;
create policy trader_market_negotiations_participant_select
  on public.trader_market_negotiations for select to authenticated
  using (
    proposer_id = auth.uid()
    or recipient_id = auth.uid()
    or exists (
      select 1 from public.trader_market_posts p
      where p.id = post_id and p.user_id = auth.uid()
    )
  );

drop policy if exists trader_market_negotiations_proposer_insert
  on public.trader_market_negotiations;
create policy trader_market_negotiations_proposer_insert
  on public.trader_market_negotiations for insert to authenticated
  with check (
    proposer_id = auth.uid()
    and (
      exists (
        select 1 from public.trader_market_posts p
        where p.id = post_id
          and p.user_id = recipient_id
          and p.user_id <> auth.uid()
          and p.is_active = true
          and p.is_negotiable = true
      )
      or exists (
        select 1 from public.trader_market_negotiations parent
        where parent.id = parent_id
          and parent.post_id = post_id
          and parent.status = 'countered'
          and parent.proposer_id = recipient_id
          and parent.recipient_id = auth.uid()
      )
    )
  );

drop policy if exists trader_market_negotiations_recipient_update
  on public.trader_market_negotiations;
create policy trader_market_negotiations_recipient_update
  on public.trader_market_negotiations for update to authenticated
  using (recipient_id = auth.uid() and status = 'pending')
  with check (recipient_id = auth.uid());

commit;
