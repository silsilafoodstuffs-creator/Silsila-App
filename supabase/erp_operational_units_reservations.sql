returns uuid
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
  v_doc public.erp_purchase_documents%rowtype;
  v_line record;
  v_count integer := 0;
  v_subtotal numeric(16,2);
  v_discount numeric(16,2);
  v_tax numeric(16,2);
