begin;
update public.erp_user_types
set description = case name_ar
  when 'ادمن' then 'إدارة النظام والصلاحيات'
  when 'مورد' then 'توريد الأصناف والأسعار'
  when 'عميل' then 'شراء الأصناف ومتابعة الطلبات'
  when 'شركة شحن' then 'إدارة الشحن والتوصيل'
  when 'مندوب' then 'البيع والتوزيع والتحصيل'
  else description end
where name_ar in ('ادمن','مورد','عميل','شركة شحن','مندوب')
  and (description is null or btrim(description)='');

alter table public.erp_user_types alter column type_code set generated by default;
update public.erp_user_types set type_code=-type_code;
with ordered_types as (
  select id,row_number() over(partition by company_id order by
    case name_ar when 'ادمن' then 1 when 'مورد' then 2 when 'عميل' then 3
      when 'شركة شحن' then 4 when 'مندوب' then 5 else 99 end,
    type_code) as next_code
  from public.erp_user_types
)
update public.erp_user_types t set type_code=o.next_code
from ordered_types o where o.id=t.id and o.next_code <= 5;
alter table public.erp_user_types alter column type_code set generated always;
select setval(pg_get_serial_sequence('public.erp_user_types','type_code'),
  greatest((select coalesce(max(type_code),1) from public.erp_user_types),1),true);
commit;