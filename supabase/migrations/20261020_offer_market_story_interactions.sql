ALTER TABLE public.offers
  ADD COLUMN IF NOT EXISTS magazine_color TEXT NOT NULL DEFAULT '#FFA015',
  ADD COLUMN IF NOT EXISTS target_governorates JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS target_districts JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS target_areas JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS target_customer_types JSONB NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS public.offer_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id BIGINT NOT NULL REFERENCES public.offers(id) ON DELETE CASCADE,
  product_id UUID REFERENCES public.products(id) ON DELETE SET NULL,
  product_name TEXT NOT NULL,
  original_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (original_price >= 0),
  offer_price NUMERIC(12,2) NOT NULL CHECK (offer_price >= 0),
  discount_percentage NUMERIC(5,2) CHECK (discount_percentage >= 0 AND discount_percentage <= 100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.trader_market_post_interactions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  post_id BIGINT NOT NULL REFERENCES public.trader_market_posts(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  interaction_type TEXT NOT NULL CHECK (interaction_type IN ('view','accept','reject')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(post_id, user_id, interaction_type)
);

CREATE TABLE IF NOT EXISTS public.story_views (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  story_id BIGINT NOT NULL REFERENCES public.stories(id) ON DELETE CASCADE,
  viewer_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(story_id, viewer_id)
);

ALTER TABLE public.offer_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trader_market_post_interactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.story_views ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "offer_items_read_active_or_owner" ON public.offer_items;
CREATE POLICY "offer_items_read_active_or_owner" ON public.offer_items
  FOR SELECT TO authenticated USING (
    EXISTS (SELECT 1 FROM public.offers o WHERE o.id = offer_id AND (o.is_active = true OR o.supplier_id = auth.uid()))
  );
DROP POLICY IF EXISTS "offer_items_supplier_manage" ON public.offer_items;
CREATE POLICY "offer_items_supplier_manage" ON public.offer_items
  FOR ALL TO authenticated USING (
    EXISTS (SELECT 1 FROM public.offers o WHERE o.id = offer_id AND o.supplier_id = auth.uid())
  ) WITH CHECK (
    EXISTS (SELECT 1 FROM public.offers o WHERE o.id = offer_id AND o.supplier_id = auth.uid())
  );

DROP POLICY IF EXISTS "market_interactions_read_authenticated" ON public.trader_market_post_interactions;
CREATE POLICY "market_interactions_read_authenticated" ON public.trader_market_post_interactions
  FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "market_interactions_insert_self" ON public.trader_market_post_interactions;
CREATE POLICY "market_interactions_insert_self" ON public.trader_market_post_interactions
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());
DROP POLICY IF EXISTS "market_interactions_delete_self" ON public.trader_market_post_interactions;
CREATE POLICY "market_interactions_delete_self" ON public.trader_market_post_interactions
  FOR DELETE TO authenticated USING (user_id = auth.uid());

DROP POLICY IF EXISTS "story_views_read_viewer_or_story_owner" ON public.story_views;
CREATE POLICY "story_views_read_viewer_or_story_owner" ON public.story_views
  FOR SELECT TO authenticated USING (
    viewer_id = auth.uid() OR EXISTS (SELECT 1 FROM public.stories s WHERE s.id = story_id AND s.user_id = auth.uid())
  );
DROP POLICY IF EXISTS "story_views_insert_self" ON public.story_views;
CREATE POLICY "story_views_insert_self" ON public.story_views
  FOR INSERT TO authenticated WITH CHECK (viewer_id = auth.uid());
